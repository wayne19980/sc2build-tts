CREATE TABLE {{schema}}.folders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    path TEXT NOT NULL,
    name TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_folders_path UNIQUE (path)
);

CREATE TABLE {{schema}}.games (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folder_id BIGINT NOT NULL REFERENCES {{schema}}.folders(id) ON DELETE CASCADE,
    file_path TEXT NOT NULL,
    file_name TEXT NOT NULL,
    file_hash VARCHAR(64) NOT NULL,
    file_size BIGINT NOT NULL,
    map_name TEXT,
    duration_sec DOUBLE PRECISION,
    game_version TEXT,
    region TEXT,
    played_at TIMESTAMPTZ,
    frames INTEGER,
    frames_per_second DOUBLE PRECISION,
    speed TEXT,
    game_type TEXT,
    raw JSONB,
    imported_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_games_file_hash UNIQUE (file_hash)
);

CREATE INDEX ix_games_folder_id ON {{schema}}.games (folder_id);
CREATE INDEX ix_games_played_at ON {{schema}}.games (played_at);

CREATE TABLE {{schema}}.game_players (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id BIGINT NOT NULL REFERENCES {{schema}}.games(id) ON DELETE CASCADE,
    pid INTEGER NOT NULL,
    name TEXT NOT NULL,
    race VARCHAR(16),
    team INTEGER,
    result VARCHAR(16),
    is_winner BOOLEAN NOT NULL DEFAULT false,
    is_human BOOLEAN NOT NULL DEFAULT false,
    uid BIGINT,
    color VARCHAR(16),
    CONSTRAINT uq_game_players_game_pid UNIQUE (game_id, pid)
);

CREATE INDEX ix_game_players_game_id ON {{schema}}.game_players (game_id);
CREATE INDEX ix_game_players_name ON {{schema}}.game_players (name);

CREATE TABLE {{schema}}.events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id BIGINT NOT NULL REFERENCES {{schema}}.games(id) ON DELETE CASCADE,
    player_id BIGINT REFERENCES {{schema}}.game_players(id) ON DELETE CASCADE,
    frame DOUBLE PRECISION NOT NULL,
    t_sec DOUBLE PRECISION NOT NULL,
    kind VARCHAR(32) NOT NULL,
    name TEXT NOT NULL,
    display_name TEXT,
    supply DOUBLE PRECISION,
    is_worker BOOLEAN NOT NULL DEFAULT false,
    payload JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE INDEX ix_events_game_player_time ON {{schema}}.events (game_id, player_id, t_sec);
CREATE INDEX ix_events_game_kind ON {{schema}}.events (game_id, kind);
CREATE INDEX ix_events_game_name ON {{schema}}.events (game_id, name);
CREATE INDEX ix_events_game_time ON {{schema}}.events (game_id, t_sec);

CREATE TABLE {{schema}}.units (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id BIGINT NOT NULL REFERENCES {{schema}}.games(id) ON DELETE CASCADE,
    player_id BIGINT NOT NULL REFERENCES {{schema}}.game_players(id) ON DELETE CASCADE,
    unit_id BIGINT NOT NULL,
    first_type TEXT NOT NULL,
    unit_type TEXT NOT NULL,
    born_t_sec DOUBLE PRECISION NOT NULL,
    died_t_sec DOUBLE PRECISION,
    is_worker BOOLEAN NOT NULL DEFAULT false,
    is_army BOOLEAN NOT NULL DEFAULT false,
    is_building BOOLEAN NOT NULL DEFAULT false,
    morphs JSONB NOT NULL DEFAULT '[]'::jsonb,
    payload JSONB NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT uq_units_game_unit UNIQUE (game_id, unit_id)
);

CREATE INDEX ix_units_game_player_born ON {{schema}}.units (game_id, player_id, born_t_sec);
CREATE INDEX ix_units_game_type ON {{schema}}.units (game_id, unit_type);
CREATE INDEX ix_units_game_died ON {{schema}}.units (game_id, died_t_sec);

CREATE TABLE {{schema}}.stats_timeline (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id BIGINT NOT NULL REFERENCES {{schema}}.games(id) ON DELETE CASCADE,
    player_id BIGINT NOT NULL REFERENCES {{schema}}.game_players(id) ON DELETE CASCADE,
    frame DOUBLE PRECISION NOT NULL,
    t_sec DOUBLE PRECISION NOT NULL,
    minerals INTEGER,
    vespene INTEGER,
    workers INTEGER,
    supply_used DOUBLE PRECISION,
    supply_made DOUBLE PRECISION,
    army_value INTEGER,
    minerals_collection_rate INTEGER,
    vespene_collection_rate INTEGER,
    resources_lost INTEGER,
    resources_killed INTEGER,
    payload JSONB NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT uq_stats_game_player_frame UNIQUE (game_id, player_id, frame)
);

CREATE INDEX ix_stats_game_player_time ON {{schema}}.stats_timeline (game_id, player_id, t_sec);

CREATE TABLE {{schema}}.agent_analyses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folder_id BIGINT REFERENCES {{schema}}.folders(id) ON DELETE CASCADE,
    game_id BIGINT REFERENCES {{schema}}.games(id) ON DELETE CASCADE,
    kind VARCHAR(32) NOT NULL,
    name TEXT,
    model TEXT,
    prompt_version TEXT,
    content JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX ix_agent_analyses_game_id ON {{schema}}.agent_analyses (game_id);
CREATE INDEX ix_agent_analyses_folder_id ON {{schema}}.agent_analyses (folder_id);
